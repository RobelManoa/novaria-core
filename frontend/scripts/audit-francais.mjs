// Seuls les mots anglais qui ne sont pas aussi du français : on retire ceux qui sont en commun.
const WORDS = new Set(
  ENGLISH_WORDS.filter(
    (word) => !SHARED_WITH_FRENCH.has(word) && !FRENCH_COLLISIONS.has(word) && !word.includes(" "),
  ),
);

/** Mots entiers d'un texte, en minuscules, sans les identifiants techniques (chiffres, tirets bas, jetons collés). */
function words(text) {
  return text
    .replace(/\/[\w./-]+/g, " ") // chemins d'API cités dans un message (/api/v1/forecasts) : identifiants, pas du texte
    .toLowerCase()
    .split(/[^\p{L}'’]+/u)
    .filter((word) => word.length > 1);
}

/** Les textes qui contiennent un mot anglais : `[{ text, words }]`. Les entrées `lang=` et `titre=` sont contrôlées à part. */
export function findEnglish(texts) {
  const found = [];
  for (const text of texts) {
    if (text.startsWith("lang=")) {
      if (text !== "lang=fr") found.push({ text, words: ["lang attendu : fr"] });
      continue;
    }
    const hits = words(text.replace(/^titre=/, "")).filter((word) => WORDS.has(word));
    if (hits.length) found.push({ text: text.slice(0, 120), words: [...new Set(hits)] });
  }
  return found;
}
